  const mkTable = (name, cols, rows) => {
    const t = newEnt('table', name);
    t.cols = cols.map(([title, op]) => ({ id: uid('c'), title, op: op || null }));
    t.rows = rows.map(r => { const cells = {}; t.cols.forEach((c, i) => { cells[c.id] = r[i]; }); return { id: uid('r'), cells }; });
    return t;
  };
